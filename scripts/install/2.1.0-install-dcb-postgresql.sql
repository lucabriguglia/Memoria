/*
    Memoria 2.1.0 — dynamic consistency boundary store schema install (PostgreSQL)

    Creates the four tables the Entity Framework Core DCB store needs, with their keys, indexes and
    foreign keys, and the append routine the store calls to append in one round trip. Run this to
    stand up a Memoria DCB store without writing a migration yourself.

    This is the DCB store, not the streamed one. The two share nothing: if you use both, run this
    alongside 1.9.0-install-postgresql.sql rather than instead of it.

    If you manage this database with EF Core migrations, do NOT run this. Your DbContext derives from
    DcbDbContext, so `dotnet ef migrations add` generates the tables from the model, and
    migrationBuilder.CreateDcbAppendRoutine(TargetModel) adds the routine. See
    docs/guides/install-the-store-schema.md.

    Assumes the default table names and the public schema. Identifiers are quoted because EF creates
    them case-sensitively. If your DbContext maps the tables elsewhere, or stores payloads as jsonb,
    do not adapt this script: install the routine with Database.EnsureDcbAppendRoutineAsync() or a
    migration instead, which generate it from your model.

    Safe to run more than once: every table and index is created IF NOT EXISTS, and the routine with
    CREATE OR REPLACE, so re-running adds only what is missing and leaves the data alone.

    The two Tag columns are created with the "C" collation, which compares byte by byte. Tags compare
    ordinally in .NET, so seat:A1 and seat:a1 are two tags; under a linguistic collation they could
    be one, and every boundary naming them would be quietly wider than the code says. Do not relax
    this.

    Upgrading from 1.8.0: the tables are unchanged, so running this script adds only the routine.
*/

/* ------------------------------------------------------------------- events */
CREATE TABLE IF NOT EXISTS public."DcbEvents" (
    "Position" bigint GENERATED BY DEFAULT AS IDENTITY,
    "EventType" character varying(255) NOT NULL,
    "Data" text NOT NULL,
    "CreatedDate" timestamp with time zone NOT NULL,
    "CreatedBy" character varying(255),
    CONSTRAINT "PK_DcbEvents" PRIMARY KEY ("Position")
);

/* --------------------------------------------------------------- snapshots */
CREATE TABLE IF NOT EXISTS public."DcbSnapshots" (
    "Id" character varying(400) NOT NULL,
    "SnapshotKind" character varying(20) NOT NULL,
    "StoreId" character varying(255) NOT NULL,
    "TagQuery" text NOT NULL,
    "ModelType" character varying(255) NOT NULL,
    "Version" integer NOT NULL,
    "LatestPosition" bigint NOT NULL,
    "Data" text NOT NULL,
    "CreatedDate" timestamp with time zone NOT NULL,
    "CreatedBy" character varying(255),
    "UpdatedDate" timestamp with time zone NOT NULL,
    "UpdatedBy" character varying(255),
    CONSTRAINT "PK_DcbSnapshots" PRIMARY KEY ("Id")
);

CREATE INDEX IF NOT EXISTS "IX_DcbSnapshots_Kind_StoreId"
    ON public."DcbSnapshots" ("SnapshotKind", "StoreId");

/* --------------------------------------------------------------- tag heads */
CREATE TABLE IF NOT EXISTS public."DcbTagHeads" (
    "Tag" character varying(255) COLLATE "C" NOT NULL,
    "Token" uuid NOT NULL,
    CONSTRAINT "PK_DcbTagHeads" PRIMARY KEY ("Tag")
);

/* --------------------------------------------------------------- event tags */
CREATE TABLE IF NOT EXISTS public."DcbEventTags" (
    "Position" bigint NOT NULL,
    "Tag" character varying(255) COLLATE "C" NOT NULL,
    CONSTRAINT "PK_DcbEventTags" PRIMARY KEY ("Tag", "Position"),
    CONSTRAINT "FK_DcbEventTags_DcbEvents_Position" FOREIGN KEY ("Position")
        REFERENCES public."DcbEvents" ("Position") ON DELETE CASCADE
);

/*
    Entity Framework Core indexes the foreign key by convention, so this index is part of the model
    the migration tooling would generate and is created here to match it. It serves the cascade
    above; no read in the store looks a tag up by position.
*/
CREATE INDEX IF NOT EXISTS "IX_DcbEventTags_Position" ON public."DcbEventTags" ("Position");

/* -------------------------------------------------------------- append routine */
/*
    The routine the store appends through: the boundary check, the tag head locks and the writes in
    one round trip. Generated by the store from the default model; the container suite compares it
    with what the store generates, so do not edit it by hand.
*/
CREATE OR REPLACE FUNCTION public.memoria_dcb_append_v1(p_affected_tags text[], p_boundary_tags text[], p_boundary_is_intersection boolean, p_after_position bigint, p_event_types text[], p_event_data text[], p_tag_event_index integer[], p_tag_values text[], p_created_date timestamp with time zone, p_created_by text, p_snapshot_id text, p_snapshot_kind text, p_snapshot_store_id text, p_snapshot_tag_query text, p_snapshot_model_type text, p_snapshot_version integer, p_snapshot_latest_position bigint, p_snapshot_data text)
 RETURNS TABLE(appended boolean, latest_position bigint)
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_latest bigint;
    v_positions bigint[];
    v_last bigint;
BEGIN
    IF cardinality(p_event_types) > 0 THEN
        IF p_boundary_tags IS NOT NULL THEN
            IF p_boundary_is_intersection THEN
                SELECT coalesce(max(matched.position), 0) INTO v_latest
                FROM (SELECT "Position" AS position FROM "DcbEventTags"
                      WHERE "Tag" = ANY (p_boundary_tags)
                      GROUP BY "Position"
                      HAVING count(*) = cardinality(p_boundary_tags)) AS matched;
            ELSE
                SELECT coalesce(max("Position"), 0) INTO v_latest
                FROM "DcbEventTags" WHERE "Tag" = ANY (p_boundary_tags);
            END IF;

            IF v_latest <> p_after_position THEN
                RETURN QUERY SELECT false, v_latest;
                RETURN;
            END IF;
        END IF;

        INSERT INTO "DcbTagHeads" ("Tag", "Token")
        SELECT affected.tag, gen_random_uuid()
        FROM unnest(p_affected_tags) WITH ORDINALITY AS affected (tag, ordinal)
        ORDER BY affected.ordinal
        ON CONFLICT ("Tag") DO NOTHING;

        PERFORM 1
        FROM unnest(p_affected_tags) WITH ORDINALITY AS affected (tag, ordinal)
        JOIN "DcbTagHeads" head ON head."Tag" = affected.tag
        ORDER BY affected.ordinal
        FOR UPDATE OF head;

        IF p_boundary_tags IS NOT NULL THEN
            IF p_boundary_is_intersection THEN
                SELECT coalesce(max(matched.position), 0) INTO v_latest
                FROM (SELECT "Position" AS position FROM "DcbEventTags"
                      WHERE "Tag" = ANY (p_boundary_tags)
                      GROUP BY "Position"
                      HAVING count(*) = cardinality(p_boundary_tags)) AS matched;
            ELSE
                SELECT coalesce(max("Position"), 0) INTO v_latest
                FROM "DcbEventTags" WHERE "Tag" = ANY (p_boundary_tags);
            END IF;

            IF v_latest <> p_after_position THEN
                RETURN QUERY SELECT false, v_latest;
                RETURN;
            END IF;
        END IF;

        UPDATE "DcbTagHeads" SET "Token" = gen_random_uuid() WHERE "Tag" = ANY (p_affected_tags);

        SELECT array_agg(nextval(pg_get_serial_sequence('"DcbEvents"', 'Position')) ORDER BY event)
        INTO v_positions
        FROM generate_series(1, cardinality(p_event_types)) AS event;

        INSERT INTO "DcbEvents" ("Position", "EventType", "Data", "CreatedDate", "CreatedBy")
        SELECT written.position, written.event_type, written.data::text, p_created_date, p_created_by
        FROM unnest(v_positions, p_event_types, p_event_data) AS written (position, event_type, data);

        INSERT INTO "DcbEventTags" ("Position", "Tag")
        SELECT v_positions[tagged.event], tagged.tag
        FROM unnest(p_tag_event_index, p_tag_values) AS tagged (event, tag);

        v_last := v_positions[cardinality(v_positions)];
    END IF;

    IF p_snapshot_id IS NOT NULL THEN
        INSERT INTO "DcbSnapshots" AS existing ("Id", "SnapshotKind", "StoreId", "TagQuery", "ModelType", "Version",
            "LatestPosition", "Data", "CreatedDate", "CreatedBy", "UpdatedDate", "UpdatedBy")
        VALUES (p_snapshot_id, p_snapshot_kind, p_snapshot_store_id, p_snapshot_tag_query,
            p_snapshot_model_type, p_snapshot_version, greatest(p_snapshot_latest_position, v_last),
            p_snapshot_data::text, p_created_date, p_created_by, p_created_date, p_created_by)
        ON CONFLICT ("Id") DO UPDATE SET
            "SnapshotKind" = EXCLUDED."SnapshotKind",
            "StoreId" = EXCLUDED."StoreId",
            "TagQuery" = EXCLUDED."TagQuery",
            "ModelType" = EXCLUDED."ModelType",
            "Version" = EXCLUDED."Version",
            "LatestPosition" = EXCLUDED."LatestPosition",
            "Data" = EXCLUDED."Data",
            "UpdatedDate" = EXCLUDED."UpdatedDate",
            "UpdatedBy" = EXCLUDED."UpdatedBy"
        WHERE existing."LatestPosition" <= EXCLUDED."LatestPosition";
    END IF;

    RETURN QUERY SELECT true, v_last;
END
$function$
;
